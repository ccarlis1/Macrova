def _head(title: str) -> list[str]:
    return [HEADER, f"# {title}", ""]


def _join(items: list[str], empty: str = "—") -> str:
    return ", ".join(items) if items else empty


def _code(items: list[str], empty: str = "—") -> str:
    return ", ".join(f"`{i}`" for i in items) if items else empty


def _area_py_files(rm: RepoMap, area: str) -> list[str]:
    return [
        p for p in rm.files
        if p.endswith(".py") and area_of(p) == area and not is_test_path(p)
    ]


def _importer_summary(rm: RepoMap, path: str, peers: bool) -> str:
    importers = sorted(rm.py.importers.get(path, set()))
    product = [display_module(p) for p in importers if is_product_path(p)]
    tests = sum(1 for p in importers if is_test_path(p))
    tooling = [p for p in importers if not is_product_path(p) and not is_test_path(p)]
    parts = [_join(product + ([display_module(p) for p in tooling] if peers else []))]
    if tests:
        parts.append(f"tests: {tests}")
    if tooling and not peers:
        parts.append(f"tooling: {len(tooling)}")
    if not product and not (peers and tooling):
        parts[0] = "— (no product importers)" if (tests or tooling) else "—"
    return " · ".join(parts)


def _py_entry(rm: RepoMap, path: str, peers: bool = False, extra: list[str] | None = None) -> list[str]:
    pf = rm.py.files[path]
    lines = [f"- **`{path}`** — {pf.doc}"]
    defs = []
    if pf.classes:
        defs.append("classes: " + _join(pf.classes))
    if pf.functions:
        defs.append("functions: " + _join(pf.functions))
    if defs:
        lines.append("  - " + "; ".join(defs))
    imports = sorted(display_module(p) for p in pf.imports)
    lines.append("  - imports: " + _join(imports))
    lines.append("  - imported by: " + _importer_summary(rm, path, peers))
    for line in extra or []:
        lines.append("  - " + line)
    return lines


def render_area(rm: RepoMap, area: str) -> str:
    out = _head(f"{AREA_TITLES[area]} — generated facts")
    out.append(f"Area `{area}` · prefixes: {_code(list(AREAS[area]))} · hand doc: `{HAND_DIR}/{area}.md`")
    out.append("")
    if area == "frontend":
        out += _render_frontend(rm)
    elif area == "tooling":
        out += _render_tooling(rm)
    else:
        route_count: dict[str, int] = {}
        for r in rm.routes:
            if r.handler:
                f = r.handler.split("::", 1)[0]
                route_count[f] = route_count.get(f, 0) + 1
        groups: dict[str, list[str]] = {}
        for path in _area_py_files(rm, area):
            groups.setdefault(path.rsplit("/", 1)[0] + "/", []).append(path)
        for directory in sorted(groups):
            out.append(f"## `{directory}`")
            out.append("")
            for path in groups[directory]:
                extra = []
                if path in route_count:
                    extra.append(f"routes: {route_count[path]} (see routes.md)")
                out += _py_entry(rm, path, extra=extra)
            out.append("")
        if area == "interfaces":
            out += _render_interfaces(rm)
    return "\n".join(out).rstrip() + "\n"


def _render_interfaces(rm: RepoMap) -> list[str]:
    out = ["## Entry points", ""]
    out += [f"- {e}" for e in entry_points(rm.py, rm.files)] or ["- —"]
    out.append("")
    flags, subs = cli_flags(rm.py)
    out += [f"## CLI flags (`{CLI_REL}`)", ""]
    if subs:
        out.append("Subcommands: " + _code(subs))
        out.append("")
    out.append(_code(flags) if flags else "—")
    out.append("")
    out += ["## MCP tools", "", "| tool | handler | delegates to |", "|---|---|---|"]
    for name, handler, calls in mcp_tools(rm.py):
        out.append(f"| `{name}` | `{handler}` | {_code(calls)} |")
    out.append("")
    return out


def _render_frontend(rm: RepoMap) -> list[str]:
    out: list[str] = []
    imported_by: dict[str, set[str]] = {p: set() for p in rm.dart}
    for df in rm.dart.values():
        for target in df.imports:
            if target in imported_by:
                imported_by[target].add(df.path)
    groups: dict[str, list[str]] = {}
    for path in sorted(rm.dart):
        groups.setdefault(path.rsplit("/", 1)[0] + "/", []).append(path)
    lib = "frontend/lib/"
    for directory in sorted(groups):
        out += [f"## `{directory}`", ""]
        for path in groups[directory]:
            df = rm.dart[path]
            classes = ", ".join(f"{c.name} [{c.kind}]" for c in df.classes) or "—"
            out.append(f"- **`{path}`** — {classes}")
            out.append("  - imports: " + _join([p[len(lib):] for p in df.imports]))
            users = sorted(p[len(lib):] for p in imported_by[path])
            shown = _join(users) if len(users) <= MAX_DART_USERS else f"{len(users)} files"
            out.append("  - imported by: " + shown)
        out.append("")
    out += ["## Backend calls", ""]
    out.append(
        "Methods of `ApiService` and the agent-feature API classes that issue HTTP calls. "
        "`{x}` marks an interpolated path segment. `in OpenAPI` checks the verb+path against "
        f"`{OPENAPI_REL}`."
    )
    out += ["", "| file | method | verb | path | in OpenAPI |", "|---|---|---|---|---|"]
    known = {(r.method, re.sub(r"\{[^}]*\}", "{}", r.path)) for r in rm.routes}
    sources = [API_SERVICE_REL] + sorted(
        p for p in rm.dart if p.startswith(AGENT_FEATURE_DIR) and "api" in p.rsplit("/", 1)[-1]
    )
    for src in sources:
        if src not in rm.dart:
            continue
        for name, verb, path in sorted(dart_backend_calls(rm.root, src)):
            norm = re.sub(r"\{[^}]*\}", "{}", path.split("?", 1)[0])
            found = "yes" if (verb, norm) in known else "NO"
            out.append(f"| `{src[len(lib):]}` | `{name}` | {verb} | `{path}` | {found} |")
    out.append("")
    return out


def _render_tooling(rm: RepoMap) -> list[str]:
    out: list[str] = []
    for prefix in ("scripts/", ".claude/hooks/", "evaluation/"):
        paths = [p for p in rm.files if p.startswith(prefix) and p.endswith(".py")]
        groups: dict[str, list[str]] = {}
        for path in paths:
            groups.setdefault(path.rsplit("/", 1)[0] + "/", []).append(path)
        for directory in sorted(groups):
            out += [f"## `{directory}`", ""]
            for path in groups[directory]:
                out += _py_entry(rm, path, peers=True)
            out.append("")
    docs = [p for p in rm.files if p.startswith("evaluation/") and p.endswith(".md")]
    out += ["## Evaluation docs (README / reports)", ""]
    out += [f"- `{p}`" for p in docs] or ["- —"]
    out.append("")
    out += ["## Tests (per directory)", ""]
    out.append("`mostly imports` counts test files in the directory importing each src area (top 3).")
    out += ["", "| directory | test files | other .py | mostly imports |", "|---|---|---|---|"]
    dirs: dict[str, list[str]] = {}
    for p in rm.files:
        if p.startswith("tests/") and p.endswith(".py"):
            dirs.setdefault(p.rsplit("/", 1)[0] + "/", []).append(p)
    for directory in sorted(dirs):
        paths = dirs[directory]
        tests = [p for p in paths if re.match(r"(test_.*|.*_test)\.py$", p.rsplit("/", 1)[-1])]
        counts: dict[str, int] = {}
        for p in paths:
            touched = {area_of(t) for t in rm.py.files[p].imports if t.startswith("src/")}
            for a in touched:
                if a:
                    counts[a] = counts.get(a, 0) + 1
        top = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:3]
        mostly = ", ".join(f"{a} ({n})" for a, n in top) or "—"
        out.append(f"| `{directory}` | {len(tests)} | {len(paths) - len(tests)} | {mostly} |")
    out.append("")
    return out



_FENCE = re.compile(r"^(```|~~~).*?^\1", re.S | re.M)
_INLINE = re.compile(r"`([^`\n]+)`")
_GLOB = set("*?[]{}<>$ ")


def _py_top_names(tree: ast.Module) -> dict[str, ast.AST | None]:
    names: dict[str, ast.AST | None] = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names[node.name] = node
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                for n in ast.walk(t):
                    if isinstance(n, ast.Name):
                        names.setdefault(n.id, None)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.setdefault(node.target.id, None)
    return names


def _py_has_symbol(tree: ast.Module | None, symbol: str) -> bool:
    if tree is None:
        return False
    parts = symbol.split(".")
    scope: dict[str, ast.AST | None] = _py_top_names(tree)
    for i, part in enumerate(parts):
        if part not in scope:
            return False
        node = scope[part]
        if i == len(parts) - 1:
            return True
        if not isinstance(node, ast.ClassDef):
            return False
        scope = {}
        for stmt in node.body:
            if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                scope[stmt.name] = stmt
            elif isinstance(stmt, ast.Assign):
                for t in stmt.targets:
                    if isinstance(t, ast.Name):
                        scope.setdefault(t.id, None)
            elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                scope.setdefault(stmt.target.id, None)
    return False


def _dart_has_symbol(source: str, symbol: str) -> bool:
    code = _strip_dart_comments(source)
    parts = symbol.split(".")
    head = re.escape(parts[0])
    if not re.search(rf"(?:\b(?:class|enum|mixin|extension|typedef)\s+{head}\b|\b{head}\s*[(<=]|\bget\s+{head}\b)", code):
        return False
    if len(parts) == 1:
        return True
    member = re.escape(parts[-1])
    return re.search(rf"(?:\b{member}\s*[(<]|\bget\s+{member}\b|\b{member}\s*[;=])", code) is not None


def _is_link_candidate(ref: str) -> bool:
    if any(ch in _GLOB for ch in ref):
        return False
    path = ref.split("::", 1)[0]
    return path.startswith(LINK_PREFIXES) or path in LINK_EXACT


def check_ref(
    root: Path,
    tracked: set[str],
    tracked_dirs: set[str],
    ref: str,
    trees: dict[str, ast.Module | None] | None = None,
) -> bool:
    """True when a backticked hand-doc reference resolves (file, ``file::symbol``, ``dir/``)."""
    path, _, symbol = ref.partition("::")
    path = re.sub(r"#.*$", "", path)
    path = re.sub(r":\d+(?:-\d+)?$", "", path)
    symbol = symbol.rstrip("()").strip()
    if path.endswith("/"):
        return path.rstrip("/") in tracked_dirs
    if path not in tracked:
        return path in tracked_dirs and not symbol
    if not symbol:
        return True
    if path.endswith(".py"):
        trees = trees if trees is not None else {}
        if path not in trees:
            try:
                trees[path] = ast.parse((root / path).read_text(encoding="utf-8"))
            except (SyntaxError, UnicodeDecodeError, OSError):
                trees[path] = None
        return _py_has_symbol(trees[path], symbol)
    if path.endswith(".dart"):
        return _dart_has_symbol((root / path).read_text(encoding="utf-8", errors="replace"), symbol)
    return True


def hand_doc_paths(root: Path) -> list[Path]:
    directory = root / HAND_DIR
    return sorted(p for p in directory.glob("*.md") if p.is_file()) if directory.is_dir() else []


def check_links(root: Path, files: list[str], py: PyIndex | None = None) -> list[str]:
    tracked = set(files)
    tracked_dirs: set[str] = set()
    for f in files:
        parts = f.split("/")
        for i in range(1, len(parts)):
            tracked_dirs.add("/".join(parts[:i]))
    trees: dict[str, ast.Module | None] = (
        {p: pf.tree for p, pf in py.files.items()} if py is not None else {}
    )
    broken: list[str] = []
    for doc in hand_doc_paths(root):
        text = _FENCE.sub("", doc.read_text(encoding="utf-8"))
        rel = doc.relative_to(root).as_posix()
        seen: set[str] = set()
        for ref in _INLINE.findall(text):
            ref = ref.strip()
            if ref in seen or not _is_link_candidate(ref):
                continue
            seen.add(ref)
            if not check_ref(root, tracked, tracked_dirs, ref, trees):
                broken.append(f"{rel}: {ref}")
    return broken


# ============================================================================ check / write


def generated_dir(root: Path) -> Path:
    return root / GENERATED_DIR


def write_outputs(root: Path, outputs: dict[str, str]) -> list[str]:
    directory = generated_dir(root)
    directory.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, content in sorted(outputs.items()):
        target = directory / name
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8", newline="\n")
            changed.append(name)
    for stale in sorted(directory.glob("*.md")):
        if stale.name not in outputs:
            stale.unlink()
            changed.append(f"{stale.name} (removed)")
    return changed


def drift(root: Path, outputs: dict[str, str]) -> tuple[list[str], list[str]]:
    """(names of stale/missing/extra files, capped unified diff lines)."""
    directory = generated_dir(root)
    stale: list[str] = []
    diff_lines: list[str] = []
    for name, content in sorted(outputs.items()):
        target = directory / name
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == content:
            continue
        stale.append(f"{GENERATED_DIR}/{name}" + (" (missing)" if current is None else ""))
        diff_lines += list(
            difflib.unified_diff(
                (current or "").splitlines(),
                content.splitlines(),
                f"a/{GENERATED_DIR}/{name}",
                f"b/{GENERATED_DIR}/{name}",
                n=1,
                lineterm="",
            )
        )
    if directory.is_dir():
        for extra in sorted(directory.glob("*.md")):
            if extra.name not in outputs:
                stale.append(f"{GENERATED_DIR}/{extra.name} (not generated; delete it)")
    if len(diff_lines) > MAX_DIFF_LINES:
        diff_lines = diff_lines[:MAX_DIFF_LINES] + [f"... ({len(diff_lines) - MAX_DIFF_LINES} more diff lines)"]
    return stale, diff_lines


def run_check(root: Path, files: list[str] | None = None) -> tuple[int, str]:
    rm = build(root, files)
    outputs = render_all(rm)
    stale, diff_lines = drift(root, outputs)
    link_files = files if files is not None else git_ls_files(root, untracked=True)
    broken = check_links(root, link_files, rm.py)
    msgs: list[str] = []
    if rm.errors:
        msgs.append("Architecture map errors:")
        msgs += [f"  {e}" for e in rm.errors]
    if stale:
        msgs.append("Generated architecture map is stale:")
        msgs += [f"  {s}" for s in stale]
        msgs += diff_lines
        msgs.append(f"Regenerate: {REGEN_CMD}  (then commit {GENERATED_DIR}/)")
    if broken:
        msgs.append(
            f"Broken repo references in hand-written docs ({HAND_DIR}/*.md) — "
            "fix the doc or the reference:"
        )
        msgs += [f"  {b}" for b in broken]
    if msgs:
        return 1, "\n".join(msgs)
    return 0, "architecture map is up to date"


# ============================================================================ stale intent

_PATH_IN_TEXT = re.compile(
    r"(?<![\w./-])((?:src|frontend/lib|evaluation|scripts|tests|\.claude/hooks)/[\w./-]*[\w/]|plan_meals\.py)"
)
_ROUTE_IN_TEXT = re.compile(r"^\|\s*(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s*\|\s*`([^`]+)`")
_ENTRY_HEADER = re.compile(r"^(?:- \*\*`|## `|\| `[^`]*` \| `)([^`]+)`")


def _git(root: Path, *args: str) -> tuple[int, str]:
    try:
        proc = subprocess.run(["git", *args], cwd=str(root), capture_output=True, text=True, check=False)
    except OSError as exc:
        return 127, str(exc)
    return proc.returncode, proc.stdout


def _area_for_ref(ref: str) -> str | None:
    if ref.endswith("/"):
        for area, prefixes in AREAS.items():
            if any(p.startswith(ref) or ref.startswith(p) for p in prefixes if p.endswith("/")):
                return area
        return None
    return area_of(ref)


def attribute_generated_change(name: str, old: str, new: str) -> dict[str, set[str]]:
    """Map area -> findings for the changed lines between two versions of a generated file.

    A changed line is attributed by the repo paths it contains; a line without a path
    inherits the path of the file entry it belongs to (the nearest preceding entry
    header). In an area file (e.g. planning.md) a line with no path at all belongs to
    that area. Route rows report ``routes changed: METHOD /path``.
    """
    findings: dict[str, set[str]] = {}
    own_area = name[:-3] if name[:-3] in AREAS else None

    def contexts(lines: list[str]) -> list[str | None]:
        ctx: list[str | None] = []
        current: str | None = None
        for line in lines:
            if line.startswith("## "):
                current = None
            m = _ENTRY_HEADER.match(line)
            if m:
                current = m.group(1).split("::", 1)[0]
            ctx.append(current)
        return ctx

    def attribute(line: str, ctx: str | None) -> None:
        if not line.strip() or line.startswith("<!--"):
            return
        route = _ROUTE_IN_TEXT.match(line)
        paths = [p for p in _PATH_IN_TEXT.findall(line)]
        if not paths and ctx:
            paths = [ctx]
        areas = {a for a in (_area_for_ref(p) for p in paths) if a}
        if not areas and own_area:
            areas = {own_area}
        for area in areas:
            if route:
                msg = f"routes changed: {route.group(1)} {route.group(2)}"
            else:
                mine = sorted(p for p in paths if _area_for_ref(p) == area)
                msg = f"generated {name} changed for {mine[0]}" if mine else f"generated {name} changed"
            findings.setdefault(area, set()).add(msg)

    old_lines, new_lines = old.splitlines(), new.splitlines()
    old_ctx, new_ctx = contexts(old_lines), contexts(new_lines)
    matcher = difflib.SequenceMatcher(None, old_lines, new_lines, autojunk=False)
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "equal":
            continue
        for i in range(i1, i2):
            attribute(old_lines[i], old_ctx[i])
        for j in range(j1, j2):
            attribute(new_lines[j], new_ctx[j])
    return findings


def parse_name_status(text: str) -> list[tuple[str, str, str | None]]:
    """Parse ``git diff --name-status -z`` into ``(status, path, new_path)`` tuples."""
    tokens = [t for t in text.split("\0") if t]
    changes: list[tuple[str, str, str | None]] = []
    i = 0
    while i + 1 < len(tokens):
        status = tokens[i]
        if status[:1] in ("R", "C") and i + 2 < len(tokens):
            changes.append((status[:1], tokens[i + 1], tokens[i + 2]))
            i += 3
        else:
            changes.append((status[:1], tokens[i + 1], None))
            i += 2
    return changes


def file_change_findings(changes: list[tuple[str, str, str | None]]) -> dict[str, set[str]]:
    """``(status, path, new_path)`` from ``git diff --name-status`` -> area -> findings."""
    findings: dict[str, set[str]] = {}
    for status, path, new_path in changes:
        if status == "C" and new_path:
            status, path, new_path = "A", new_path, None
        if status == "R" and new_path:
            for p in (path, new_path):
                if is_mapped_file(p):
                    findings.setdefault(area_of(p) or "", set()).add(f"renamed {path} -> {new_path}")
        elif status in ("A", "D") and is_mapped_file(path):
            verb = "new file" if status == "A" else "deleted file"
            findings.setdefault(area_of(path) or "", set()).add(f"{verb} {path}")
    findings.pop("", None)
    return findings


def stale_intent(root: Path, base: str, strict: bool) -> int:
    rc, _ = _git(root, "rev-parse", "--git-dir")
    if rc != 0:
        print("stale-intent: not a git checkout; skipping")
        return 0
    rc, mb = _git(root, "merge-base", base, "HEAD")
    if rc != 0 or not mb.strip():
        print(f"stale-intent: cannot find merge-base of {base!r} and HEAD; skipping")
        return 0
    mb = mb.strip()
    rc, out = _git(root, "diff", "--name-status", "-M", "-z", mb)
    changes = parse_name_status(out) if rc == 0 else []
    _, untracked = _git(root, "ls-files", "--others", "--exclude-standard", "-z")
    changes += [("A", p, None) for p in untracked.split("\0") if p]
    changed_paths = {c[1] for c in changes} | {c[2] for c in changes if c[2]}

    findings = file_change_findings(changes)
    gen_changed = sorted(p for p in changed_paths if p.startswith(GENERATED_DIR + "/") and p.endswith(".md"))
    for rel in gen_changed:
        rc, old = _git(root, "show", f"{mb}:{rel}")
        old = old if rc == 0 else ""
        target = root / rel
        new = target.read_text(encoding="utf-8") if target.is_file() else ""
        for area, msgs in attribute_generated_change(rel.rsplit("/", 1)[-1], old, new).items():
            findings.setdefault(area, set()).update(msgs)

    flagged = 0
    gha = os.environ.get("GITHUB_ACTIONS") == "true"
    for area in AREAS:
        msgs = sorted(findings.get(area, set()))
        hand = f"{HAND_DIR}/{area}.md"
        if not msgs or hand in changed_paths:
            continue
        flagged += 1
        shown = msgs[:5] + ([f"+{len(msgs) - 5} more"] if len(msgs) > 5 else [])
        message = f"{area}: {'; '.join(shown)} — review {hand}"
        print(f"[stale-intent] {message}")
        if gha:
            print(f"::warning file={hand}::{message}")
    if not flagged:
        print(f"stale-intent: no hand-written map docs need review (base {base})")
    return 1 if (strict and flagged) else 0


# ============================================================================ main


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if generated files are stale or links broken")
    mode.add_argument("--stale-intent", action="store_true", help="advisory: hand docs that may need review")
    parser.add_argument("--base", default="main", help="base ref for --stale-intent (default: main)")
    parser.add_argument("--strict", action="store_true", help="--stale-intent exits 1 when anything is flagged")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root.resolve()

    if args.stale_intent:
        return stale_intent(root, args.base, args.strict)
    if args.check:
        rc, message = run_check(root)
        print(message, file=sys.stderr if rc else sys.stdout)
        return rc

    rm = build(root)
    changed = write_outputs(root, render_all(rm))
    print("wrote: " + ", ".join(changed) if changed else "generated architecture map already up to date")
    broken = check_links(root, git_ls_files(root, untracked=True), rm.py)
    if broken:
        print("warning: broken repo references in hand-written docs:", file=sys.stderr)
        for b in broken:
            print(f"  {b}", file=sys.stderr)
    if rm.errors:
        for e in rm.errors:
            print(f"error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

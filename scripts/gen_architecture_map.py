@dataclass
class PyFile:
    path: str
    module: str
    tree: ast.Module | None
    doc: str = "—"
    classes: list[str] = field(default_factory=list)
    functions: list[str] = field(default_factory=list)
    raw_imports: list[tuple[str, int, list[str]]] = field(default_factory=list)
    imports: set[str] = field(default_factory=set)  # resolved repo paths
    parse_error: str | None = None


def _first_line(doc: str | None, limit: int = 160) -> str:
    if not doc:
        return "—"
    for line in doc.strip().splitlines():
        line = line.strip()
        if line:
            line = line.replace("|", "\\|")
            return line if len(line) <= limit else line[: limit - 1].rstrip() + "…"
    return "—"


def parse_python(root: Path, path: str) -> PyFile:
    pf = PyFile(path=path, module=module_name(path), tree=None)
    try:
        source = (root / path).read_text(encoding="utf-8")
        tree = ast.parse(source, filename=path)
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        pf.parse_error = type(exc).__name__
        return pf
    pf.tree = tree
    pf.doc = _first_line(ast.get_docstring(tree))
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            pf.classes.append(node.name)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            pf.functions.append(node.name)
    pf.classes.sort()
    pf.functions.sort()
    for node in _statements(tree.body):
        if isinstance(node, ast.Import):
            for alias in node.names:
                pf.raw_imports.append((alias.name, 0, []))
        elif isinstance(node, ast.ImportFrom):
            pf.raw_imports.append((node.module or "", node.level, [a.name for a in node.names]))
    return pf


_BODY_FIELDS = ("body", "orelse", "finalbody", "handlers", "cases")


def _statements(body: list[ast.stmt]):
    """Every statement, at any nesting depth (imports are statements, so this finds lazy
    imports inside functions too) without walking expressions -- much cheaper than ast.walk."""
    stack = list(reversed(body))
    while stack:
        node = stack.pop()
        yield node
        for name in _BODY_FIELDS:
            children = getattr(node, name, None)
            if isinstance(children, list):
                stack.extend(reversed(children))


class PyIndex:
    """All parsed Python files plus resolved internal import edges (path -> paths)."""

    def __init__(self, root: Path, py_paths: list[str]):
        self.root = root
        self.files: dict[str, PyFile] = {p: parse_python(root, p) for p in py_paths}
        self.by_module: dict[str, str] = {}
        for p in py_paths:
            self.by_module.setdefault(module_name(p), p)
        for pf in self.files.values():
            pf.imports = self._resolve(pf)
        self.importers: dict[str, set[str]] = {p: set() for p in py_paths}
        for pf in self.files.values():
            for target in pf.imports:
                self.importers[target].add(pf.path)

    def _lookup(self, dotted: str) -> str | None:
        return self.by_module.get(dotted)

    def _longest(self, dotted: str) -> str | None:
        parts = dotted.split(".")
        for end in range(len(parts), 0, -1):
            hit = self._lookup(".".join(parts[:end]))
            if hit:
                return hit
        return None

    def _sibling(self, pf: PyFile, name: str) -> str | None:
        """Script-style import of a file in the same directory (``import _common``)."""
        head = name.split(".")[0]
        directory = pf.path.rsplit("/", 1)[0] if "/" in pf.path else ""
        candidate = f"{directory}/{head}.py" if directory else f"{head}.py"
        return candidate if candidate in self.files and candidate != pf.path else None

    def _resolve(self, pf: PyFile) -> set[str]:
        out: set[str] = set()
        is_pkg = pf.path.endswith("__init__.py")
        for module, level, names in pf.raw_imports:
            if level:
                base_parts = pf.module.split(".")
                if not is_pkg:
                    base_parts = base_parts[:-1]
                if level > 1:
                    base_parts = base_parts[: len(base_parts) - (level - 1)]
                base = ".".join(base_parts + ([module] if module else []))
            else:
                base = module
            hits: list[str] = []
            if names:  # from X import a, b
                for name in names:
                    hit = self._lookup(f"{base}.{name}") if base else None
                    if hit:
                        hits.append(hit)
                if not hits and base:
                    hit = self._lookup(base) or self._longest(base)
                    if hit:
                        hits.append(hit)
            elif base:
                hit = self._longest(base)
                if hit:
                    hits.append(hit)
            if not hits and not level and base:
                hit = self._sibling(pf, base)
                if hit:
                    hits.append(hit)
            out.update(h for h in hits if h != pf.path)
        return out



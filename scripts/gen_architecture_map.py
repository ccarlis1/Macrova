@dataclass
class RepoMap:
    root: Path
    files: list[str]
    py: PyIndex
    dart: dict[str, DartFile]
    routes: list[Route]
    entities: list[Entity]
    errors: list[str]


def build(root: Path, files: list[str] | None = None) -> RepoMap:
    files = sorted(files if files is not None else git_ls_files(root, untracked=True))
    errors: list[str] = []
    for path in files:
        if must_be_mapped(path):
            hits = areas_of(path)
            if len(hits) != 1:
                why = "is not under any area" if not hits else f"is under several areas {hits}"
                errors.append(
                    f"unmapped file: {path} {why}; add its prefix to AREAS in {SCRIPT_REL}"
                )
    py_paths = [f for f in files if f.endswith(".py")]
    py = PyIndex(root, py_paths)
    for pf in py.files.values():
        if pf.parse_error and is_mapped_file(pf.path):
            errors.append(f"cannot parse {pf.path}: {pf.parse_error}")
    package = dart_package_name(root)
    dart = {
        f: parse_dart(root, f, package)
        for f in files
        if f.startswith("frontend/lib/") and f.endswith(".dart")
    }
    routes, route_errors = load_routes(root, py, files)
    errors += route_errors
    return RepoMap(root, files, py, dart, routes, collect_entities(py), errors)



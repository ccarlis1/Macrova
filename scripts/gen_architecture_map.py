_DART_DECL = re.compile(
    r"^(?P<mods>(?:(?:abstract|sealed|final|base|interface|mixin)\s+)*)"
    r"(?P<kw>class|enum|mixin|extension)\s+(?P<name>\w+)?(?P<header>[^{;]*)\{",
    re.M,
)
_DART_IMPORT = re.compile(r"""^\s*(?:import|export)\s+['"]([^'"]+)['"]""", re.M)


@dataclass
class DartClass:
    name: str
    kind: str


@dataclass
class DartFile:
    path: str
    classes: list[DartClass]
    imports: list[str]  # repo paths within frontend/lib


def _dart_clause(header: str, word: str) -> str:
    match = re.search(rf"\b{word}\s+(.+?)(?=\b(?:extends|with|implements|on)\b|$)", header, re.S)
    return match.group(1).strip() if match else ""


def dart_kind(path: str, kw: str, header: str, name: str = "") -> str:
    if kw == "enum":
        return "Enum"
    if kw in ("mixin", "extension"):
        return "other"
    extends = _dart_clause(header, "extends")
    mixins = _dart_clause(header, "with")
    base = re.split(r"[<\s]", extends, maxsplit=1)[0] if extends else ""
    fname = path.rsplit("/", 1)[-1]
    if "ChangeNotifier" in (base, *re.findall(r"\w+", mixins)):
        return "Provider"
    is_widget_base = base in ("StatefulWidget", "StatelessWidget")
    if is_widget_base and "/screens/" in path:
        return "Screen"
    if is_widget_base and fname.endswith("_screen.dart") and name.endswith("Screen"):
        return "Screen"  # feature folders (features/agent/*_screen.dart)
    if is_widget_base or base == "State" or base.endswith("Widget") or base.endswith("Painter"):
        return "Widget"
    if "/models/" in path or fname.endswith(("_models.dart", "_model.dart")):
        return "Model"
    if "/services/" in path or fname.endswith(("_api.dart", "_service.dart")):
        return "Service"
    return "other"


def _strip_dart_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"(?m)//.*$", "", text)


def parse_dart(root: Path, path: str, package: str | None) -> DartFile:
    text = (root / path).read_text(encoding="utf-8")
    code = _strip_dart_comments(text)
    classes: list[DartClass] = []
    for m in _DART_DECL.finditer(code):
        name = m.group("name")
        if not name or name.startswith("_") or (m.group("kw") == "extension" and name == "on"):
            continue
        classes.append(
            DartClass(name=name, kind=dart_kind(path, m.group("kw"), m.group("header"), name))
        )
    classes.sort(key=lambda c: c.name)
    imports: set[str] = set()
    directory = path.rsplit("/", 1)[0]
    for target in _DART_IMPORT.findall(code):
        resolved: str | None = None
        if package and target.startswith(f"package:{package}/"):
            resolved = "frontend/lib/" + target[len(f"package:{package}/"):]
        elif ":" not in target:
            resolved = os.path.normpath(f"{directory}/{target}").replace(os.sep, "/")
        if resolved and resolved.startswith("frontend/lib/"):
            imports.add(resolved)
    return DartFile(path=path, classes=classes, imports=sorted(imports))


def dart_package_name(root: Path) -> str | None:
    pubspec = root / "frontend" / "pubspec.yaml"
    try:
        for line in pubspec.read_text(encoding="utf-8").splitlines():
            m = re.match(r"name:\s*([\w]+)", line)
            if m:
                return m.group(1)
    except OSError:
        pass
    return None


def _match_close(text: str, start: int, open_ch: str, close_ch: str) -> int:
    """Index of the bracket closing the one at *start* (naive; ignores strings)."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i
    return len(text) - 1


_DART_METHOD = re.compile(r"(?:static\s+)?Future\s*<")
_DART_HTTP = re.compile(r"\b(?:http|client|_client|_http)\.(get|post|put|patch|delete)\s*\(")
_DART_API_LITERAL = re.compile(r"""['"]([^'"\n]*?/api/[^'"\n]*)['"]""")


def _dart_path_template(literal: str) -> str:
    path = literal[literal.index("/api/"):]
    path = re.sub(r"\$\{[^}]*?(\w+)\)?\}", r"{\1}", path)  # ${Uri.encodeComponent(id)} -> {id}
    path = re.sub(r"\$(\w+)", r"{\1}", path)
    return path


def dart_backend_calls(root: Path, path: str) -> list[tuple[str, str, str]]:
    """(method name, VERB, path template) for each HTTP call in each Future-returning method."""
    code = _strip_dart_comments((root / path).read_text(encoding="utf-8"))
    out: list[tuple[str, str, str]] = []
    pos = 0
    while True:
        m = _DART_METHOD.search(code, pos)
        if not m:
            break
        lt = m.end() - 1
        gt = _match_close(code, lt, "<", ">")
        nm = re.match(r"\s*(\w+)\s*\(", code[gt + 1:])
        if not nm:
            pos = gt + 1
            continue
        name = nm.group(1)
        paren = gt + 1 + nm.end() - 1
        close = _match_close(code, paren, "(", ")")
        brace = re.match(r"\s*(?:async\s*)?\{", code[close + 1:])
        if not brace:
            pos = close + 1
            continue
        body_start = close + 1 + brace.end() - 1
        body_end = _match_close(code, body_start, "{", "}")
        body = code[body_start:body_end]
        verbs = sorted({v.upper() for v in _DART_HTTP.findall(body)})
        paths = sorted({_dart_path_template(lit) for lit in _DART_API_LITERAL.findall(body)})
        if verbs or paths:
            for verb in verbs or ["?"]:
                for p in paths or ["?"]:
                    out.append((name, verb, p))
        pos = body_end + 1
    return out



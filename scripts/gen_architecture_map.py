@dataclass
class Route:
    method: str
    path: str
    operation_id: str
    tags: str
    request: str
    response: str
    handler: str | None


def _schema_name(schema: dict | None) -> str:
    if not isinstance(schema, dict) or not schema:
        return "—"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if schema.get("type") == "array":
        return f"array[{_schema_name(schema.get('items'))}]"
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            names = [_schema_name(s) for s in schema[key] if s.get("type") != "null"]
            return " \\| ".join(names) if names else "—"
    if "type" in schema:
        return f"inline {schema['type']}"
    return "inline"


def _body_schema(container: dict | None) -> str:
    if not isinstance(container, dict):
        return "—"
    content = container.get("content") or {}
    media = content.get("application/json") or next(iter(content.values()), {}) if content else {}
    return _schema_name(media.get("schema") if isinstance(media, dict) else None)


def _route_functions(py: PyIndex, api_paths: list[str]) -> dict[str, list[tuple[str, ast.AST]]]:
    found: dict[str, list[tuple[str, ast.AST]]] = {}
    for path in api_paths:
        tree = py.files[path].tree
        if tree is None:
            continue
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                found.setdefault(node.name, []).append((path, node))
    return found


def _decorated_with(node: ast.AST, method: str) -> bool:
    for dec in getattr(node, "decorator_list", []):
        target = dec.func if isinstance(dec, ast.Call) else dec
        if isinstance(target, ast.Attribute) and target.attr == method:
            return True
    return False


def handler_name(operation_id: str, path: str, method: str) -> str | None:
    """FastAPI default operationId is ``re.sub(r"\\W", "_", name + path) + "_" + method``."""
    suffix = re.sub(r"\W", "_", path) + "_" + method.lower()
    if operation_id.endswith(suffix) and len(operation_id) > len(suffix):
        return operation_id[: -len(suffix)]
    return None


def load_routes(root: Path, py: PyIndex, files: list[str]) -> tuple[list[Route], list[str]]:
    errors: list[str] = []
    spec_path = root / OPENAPI_REL
    if not spec_path.is_file():
        return [], [f"missing {OPENAPI_REL}"]
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    api_paths = [f for f in files if f.startswith("src/api/") and f.endswith(".py")]
    funcs = _route_functions(py, api_paths)
    routes: list[Route] = []
    for path, ops in sorted((spec.get("paths") or {}).items()):
        for method, op in sorted(ops.items()):
            if method not in HTTP_METHODS or not isinstance(op, dict):
                continue
            op_id = op.get("operationId") or ""
            name = handler_name(op_id, path, method)
            handler: str | None = None
            if name is None:
                errors.append(
                    f"route {method.upper()} {path}: operationId {op_id!r} is not FastAPI's "
                    "default '<function>_<path>_<method>' form; cannot resolve the handler"
                )
            else:
                candidates = funcs.get(name, [])
                if len(candidates) > 1:
                    candidates = [c for c in candidates if _decorated_with(c[1], method)]
                if len(candidates) == 1:
                    handler = f"{candidates[0][0]}::{name}"
                else:
                    where = "no top-level function" if not candidates else "ambiguous functions"
                    errors.append(
                        f"route {method.upper()} {path}: {where} named {name!r} in src/api/*.py "
                        f"(operationId {op_id!r})"
                    )
            responses = op.get("responses") or {}
            ok = responses.get("200") or responses.get("201")
            routes.append(
                Route(
                    method=method.upper(),
                    path=path,
                    operation_id=op_id,
                    tags=", ".join(op.get("tags") or []) or "—",
                    request=_body_schema(op.get("requestBody")),
                    response=_body_schema(ok),
                    handler=handler,
                )
            )
    return routes, errors



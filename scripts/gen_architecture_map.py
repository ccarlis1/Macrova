def src_package(path: str) -> str | None:
    """``src/planning/x.py`` -> ``planning``; ``src/cli.py`` -> ``cli``."""
    if not path.startswith("src/"):
        return None
    rest = path[len("src/"):]
    if "/" in rest:
        return rest.split("/", 1)[0]
    return rest[:-3] if rest.endswith(".py") else rest



_DATACLASS = {"dataclass"}
_PYDANTIC_ROOTS = {"BaseModel", "RootModel", "BaseSettings"}
_ENUM_ROOTS = {"Enum", "IntEnum", "StrEnum", "Flag", "IntFlag"}
_TYPEDDICT_ROOTS = {"TypedDict"}


def _base_names(node: ast.ClassDef) -> list[str]:
    out = []
    for base in node.bases:
        target = base.value if isinstance(base, ast.Subscript) else base
        if isinstance(target, ast.Name):
            out.append(target.id)
        elif isinstance(target, ast.Attribute):
            out.append(target.attr)
    return out


def _is_dataclass(node: ast.ClassDef) -> bool:
    for dec in node.decorator_list:
        target = dec.func if isinstance(dec, ast.Call) else dec
        name = target.id if isinstance(target, ast.Name) else getattr(target, "attr", "")
        if name in _DATACLASS:
            return True
    return False


def _fields(node: ast.ClassDef, kind: str) -> list[str]:
    names: list[str] = []
    for stmt in node.body:
        if kind == "Enum":
            if isinstance(stmt, ast.Assign):
                names += [t.id for t in stmt.targets if isinstance(t, ast.Name)]
            elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value:
                names.append(stmt.target.id)
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            ann = ast.unparse(stmt.annotation) if hasattr(ast, "unparse") else ""
            if "ClassVar" in ann:
                continue
            names.append(stmt.target.id)
    return [n for n in names if not (n.startswith("_") and n.endswith("_"))]


@dataclass
class Entity:
    name: str
    kind: str
    path: str
    fields: list[str]


def collect_entities(py: PyIndex) -> list[Entity]:
    classes: list[tuple[str, ast.ClassDef]] = []
    for path in sorted(py.files):
        if not path.startswith("src/"):
            continue
        tree = py.files[path].tree
        if tree is None:
            continue
        classes += [(path, n) for n in tree.body if isinstance(n, ast.ClassDef)]
    kinds: dict[str, str] = {}
    by_name_kind: dict[str, str] = {}
    changed = True
    while changed:  # transitive: subclasses of repo pydantic models / enums / TypedDicts
        changed = False
        for path, node in classes:
            key = f"{path}::{node.name}"
            if key in kinds:
                continue
            bases = set(_base_names(node))
            kind = None
            if bases & _PYDANTIC_ROOTS or any(by_name_kind.get(b) == "pydantic" for b in bases):
                kind = "pydantic"
            elif bases & _ENUM_ROOTS or any(by_name_kind.get(b) == "Enum" for b in bases):
                kind = "Enum"
            elif bases & _TYPEDDICT_ROOTS or any(by_name_kind.get(b) == "TypedDict" for b in bases):
                kind = "TypedDict"
            elif _is_dataclass(node):
                kind = "dataclass"
            if kind:
                kinds[key] = kind
                if kind != "dataclass":
                    by_name_kind.setdefault(node.name, kind)
                changed = True
    out = []
    for path, node in classes:
        kind = kinds.get(f"{path}::{node.name}")
        if kind:
            out.append(Entity(node.name, kind, path, _fields(node, kind)))
    return sorted(out, key=lambda e: (area_of(e.path) or "", e.path, e.name))



def git_ls_files(root: Path, untracked: bool = False) -> list[str]:
    """Tracked files (index) that still exist on disk, sorted, repo-relative POSIX.

    ``untracked=True`` adds untracked files that are not gitignored. Both the generated
    facts and the hand-doc link check use it, so a new file is mapped (and the Stop hook
    sees the drift) before its first ``git add``; gitignored files, absent in CI, never
    count.
    """
    cmd = ["git", "ls-files", "-z"] + (["--cached", "--others", "--exclude-standard"] if untracked else [])
    proc = subprocess.run(cmd, cwd=str(root), capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise SystemExit(f"git ls-files failed in {root.name}: {proc.stderr.strip()}")
    files = [f for f in proc.stdout.split("\0") if f]
    return sorted(f for f in files if (root / f).is_file())


def area_of(path: str) -> str | None:
    """First area whose prefixes contain *path* (prefixes do not overlap by construction)."""
    for area, prefixes in AREAS.items():
        for prefix in prefixes:
            if prefix.endswith("/"):
                if path.startswith(prefix):
                    return area
            elif path == prefix:
                return area
    return None


def areas_of(path: str) -> list[str]:
    out = []
    for area, prefixes in AREAS.items():
        for prefix in prefixes:
            if (prefix.endswith("/") and path.startswith(prefix)) or path == prefix:
                out.append(area)
                break
    return out


def is_mapped_file(path: str) -> bool:
    """Files the map covers (used for area membership and stale-intent)."""
    area = area_of(path)
    if area is None:
        return False
    if area == "frontend":
        return path.endswith(".dart")
    if path.startswith("evaluation/"):
        return path.endswith(".py") or path.endswith(".md")
    return path.endswith(".py")


def must_be_mapped(path: str) -> bool:
    return (path.startswith("src/") and path.endswith(".py")) or (
        path.startswith("frontend/lib/") and path.endswith(".dart")
    )


def module_name(path: str) -> str:
    """Dotted module path for a .py file (``__init__`` collapses to the package)."""
    parts = path[:-3].split("/")
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def display_module(path: str) -> str:
    """Module path for display; non-importable locations (e.g. .claude/hooks) use the file path."""
    if path.startswith("."):
        return path
    return module_name(path)



def cli_flags(py: PyIndex) -> tuple[list[str], list[str]]:
    pf = py.files.get(CLI_REL)
    if not pf or pf.tree is None:
        return [], []
    flags: set[str] = set()
    subcommands: set[str] = set()
    for node in ast.walk(pf.tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        strs = [a.value for a in node.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]
        if node.func.attr == "add_argument" and strs:
            opts = [s for s in strs if s.startswith("-")]
            flags.add(" / ".join(sorted(opts, key=lambda s: (-len(s), s))) if opts else f"<{strs[0]}>")
        elif node.func.attr == "add_parser" and strs:
            subcommands.add(strs[0])
    return sorted(flags), sorted(subcommands)


def mcp_tools(py: PyIndex) -> list[tuple[str, str, list[str]]]:
    """(tool name, handler ref, delegated repo calls) for every ``@x.tool(...)`` function."""
    out = []
    for path in sorted(py.files):
        if not path.startswith(MCP_DIR) or py.files[path].tree is None:
            continue
        tree = py.files[path].tree
        aliases: dict[str, str] = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module:
                for a in node.names:
                    target = py.by_module.get(f"{node.module}.{a.name}")
                    if target:
                        aliases[a.asname or a.name] = target
            elif isinstance(node, ast.Import):
                for a in node.names:
                    target = py.by_module.get(a.name)
                    if target and a.asname:
                        aliases[a.asname] = target

        def visit(body: list[ast.stmt], prefix: str) -> None:
            for node in body:
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    qual = f"{prefix}{node.name}"
                    for dec in getattr(node, "decorator_list", []):
                        if (
                            isinstance(dec, ast.Call)
                            and isinstance(dec.func, ast.Attribute)
                            and dec.func.attr == "tool"
                        ):
                            name = node.name
                            for kw in dec.keywords:
                                if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                                    name = str(kw.value.value)
                            calls = sorted(
                                {
                                    f"{aliases[c.func.value.id]}::{c.func.attr}"
                                    for c in ast.walk(node)
                                    if isinstance(c, ast.Call)
                                    and isinstance(c.func, ast.Attribute)
                                    and isinstance(c.func.value, ast.Name)
                                    and c.func.value.id in aliases
                                }
                            )
                            out.append((name, f"{path}::{qual}", calls))
                    visit(node.body, qual + ".")

        visit(tree.body, "")
    return sorted(out)


def entry_points(py: PyIndex, files: list[str]) -> list[str]:
    out = []
    for path in files:
        if area_of(path) != "interfaces" or not path.endswith(".py"):
            continue
        tree = py.files[path].tree
        if path.endswith("__main__.py"):
            out.append(f"`{path}` (`python -m {module_name(path).rsplit('.', 1)[0]}`)")
            continue
        if tree is None:
            continue
        for node in tree.body:
            if (
                isinstance(node, ast.If)
                and isinstance(node.test, ast.Compare)
                and isinstance(node.test.left, ast.Name)
                and node.test.left.id == "__name__"
            ):
                out.append(f"`{path}` (`__main__` guard)")
                break
    return sorted(out)


